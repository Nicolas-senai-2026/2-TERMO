CREATE TABLE USUARIO (
    ID_USUARIO INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

SELECT * 
FROM USUARIO;

CREATE TABLE LIVRO (
    ID_LIVRO INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICADO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0, CHECK >= 0
);

SELECT * 
FROM LIVRO;

CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NOT NULL,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO', CHECK,
    ID_USUARIO INT Foreign Key (ID_USUARIO) REFERENCES (ID_USUARIO),
    ID_LIVRO INT Foreign Key (ID_LIVRO) REFERENCES (ID_LIVRO)
);

