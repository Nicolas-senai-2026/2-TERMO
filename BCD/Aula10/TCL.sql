-- SEM TRANSACAO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSACAO: PODE CONFIRMAR TUDO OU DESFAZER TUDO

-- ESTRUTURA DO CONCEITO
START TRANSACTION
-- COMANDOS SQL
-- INSERT, UPDATE, DELETE, SELECT
COMMIT; -- CONFIRMA TODAS AS ALTERACOES
ROLLBACK; -- DESFAZ TODAS AS ALTERACOES

-- EX 2: COMMIT - CONFIRMANDO ALTERACOES REALIZADAS

START TRANSACTION;
UPDATE PRODUTO
SET PRECO = 8.50
WHERE ID_PRODUTO = 1;

SELECT * FROM produto WHERE ID_PRODUTO = 1;
UPDATE produto
SET PRECO = 9.00
WHERE ID_PRODUTO = 1;
SELECT * FROM produto WHERE ID_PRODUTO = 1;
COMMIT;

-- EX 3: ROLLBACK - DESFAZER ALTERACOES AINDA NAO CONFIRMADAS

START TRANSACTION;
SELECT * FROM produto WHERE ID_PRODUTO = 1;
UPDATE PRODUTO
SET PRECO = 5000.00
WHERE ID_PRODUTO = 1;
SELECT * FROM produto WHERE ID_PRODUTO = 1;
ROLLBACK;
